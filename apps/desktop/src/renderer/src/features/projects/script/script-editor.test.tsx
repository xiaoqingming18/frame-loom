import { cleanup, render, screen, fireEvent, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { ScriptDocument, createEditableScript } from '@frame-loom/contracts';
import raw from '../../../../../../../../packages/contracts/fixtures/standard-script-short.json?raw';
import { ScriptEditor } from './script-editor';
afterEach(cleanup);
Range.prototype.getClientRects = () => [] as unknown as DOMRectList;
Range.prototype.getBoundingClientRect = () => new DOMRect();
const scrollIntoView = vi.fn();
HTMLElement.prototype.scrollIntoView = scrollIntoView;
it('U02/U03 只读权威值、大纲定位，独立字段可编辑，无旧菜单', async () => {
  const doc = createEditableScript(ScriptDocument.parse(JSON.parse(raw)));
  const changed = vi.fn();
  render(<ScriptEditor document={doc} onChange={changed} onError={vi.fn()} />);
  await screen.findByRole('heading', { name: '《夜班便利店》第1集剧本' });
  expect(screen.queryByRole('combobox', { name: '段落类型' })).toBeNull();
  expect(screen.getAllByRole('textbox', { name: '说话人' })).toHaveLength(2);
  expect(screen.getByText('冷色写实').closest('[contenteditable="true"]')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: /1-2.*便利店/ }));
  expect(scrollIntoView).toHaveBeenCalled();
  fireEvent.click(screen.getAllByRole('button', { name: '切换内外' })[0]);
  await waitFor(() => expect(changed).toHaveBeenCalled());
});
